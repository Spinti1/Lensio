import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
const source=await readFile(new URL('../web/protocol.js',import.meta.url),'utf8');
const {encodeCode,decodeCode,gatherIce}=await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
const offer={type:'offer',sdp:'v=0\r\na=ice-ufrag:test\r\na=candidate:test 1 udp 1 192.0.2.1 1000 typ host\r\n'};
const code=await encodeCode(offer);
assert.deepEqual(await decodeCode(code,'offer'),offer);
assert.deepEqual(await decodeCode('https://example.com/#offer='+code,'offer'),offer);
const plain='L1.'+Buffer.from(JSON.stringify({v:1,...offer})).toString('base64url');
assert.deepEqual(await decodeCode(plain,'offer'),offer);
await assert.rejects(()=>decodeCode(code,'answer'),/wrong pairing step/);
for(const invalid of ['','L1.????','x'.repeat(33000),'javascript:alert(1)'])await assert.rejects(()=>decodeCode(invalid,'offer'));
const huge=await encodeCode({type:'offer',sdp:'v=0'+'x'.repeat(60000)});
await assert.rejects(()=>decodeCode(huge,'offer'),/too large/);
await gatherIce({iceGatheringState:'complete'});
const ice=new EventTarget();ice.iceGatheringState='gathering';
const done=gatherIce(ice,100);ice.iceGatheringState='complete';ice.dispatchEvent(new Event('icegatheringstatechange'));await done;
await assert.rejects(()=>gatherIce(Object.assign(new EventTarget(),{iceGatheringState:'gathering'}),5),/network candidates/);
console.log('PASS: plain/compressed pairing round trips, link import, wrong-step rejection, size bounds, ICE completion and timeout');
